#!/usr/bin/env python3
"""
Antigravity Video Studio — Video Subclip & Landmark Semantic Analyzer
=====================================================================
Permanently solves the "Missed Scenes in Long Clips" flaw.

For any video clip >= 12.0s, this script:
1. Takes the 6-frame contact strip (`.proxies/<stem>_strip.jpg`) generated by `ingest_and_sync_media.py`.
2. Calls Gemini 3.8 Flash Vision to semantically analyze the 6 frames across the clip's duration.
3. Detects head turns, camera pans, rider stops, U-turns, text signs, and prominent landmarks
   (hotels, restaurants, statues, medieval walls, coastal vistas).
4. Caches the result in `.proxies/<stem>_subclips.json` (zero redundant API calls).
5. Updates `project_manifest.json` under each media item with:
   - `sub_clips`: list of {segment: [start_s, end_s], description: str}
   - `landmarks`: list of {name: str, type: str, timestamp_range: [start_s, end_s]}
6. Injects the parsed subclip timeline directly into `Storyboard.md` under Section 3.
"""

import argparse
import json
import os
import re
import sys
from pathlib import Path
from PIL import Image

try:
    from google import genai
    from google.genai import types
except ImportError:
    genai = None

VISION_MODEL = "gemini-3.8-flash"


def analyze_clip_strip(strip_path: Path, duration_s: float, client) -> dict:
    """Uses Gemini 3.8 Flash to extract structured sub-events and landmarks from a contact strip."""
    cache_path = strip_path.parent / f"{strip_path.stem.replace('_strip', '')}_subclips.json"
    if cache_path.exists():
        try:
            with open(cache_path, "r", encoding="utf-8") as f:
                cached = json.load(f)
                if "sub_events" in cached:
                    return cached
        except Exception:
            pass

    if client is None or not strip_path.exists():
        return {}

    img = Image.open(strip_path)
    prompt = f"""
This is a 3x2 contact sheet showing 6 evenly spaced frames across a {duration_s:.1f}-second cycling video clip:
- Frame 1 (top-left): ~{duration_s * 0.05:.1f}s
- Frame 2 (top-center): ~{duration_s * 0.23:.1f}s
- Frame 3 (top-right): ~{duration_s * 0.42:.1f}s
- Frame 4 (bottom-left): ~{duration_s * 0.60:.1f}s
- Frame 5 (bottom-center): ~{duration_s * 0.78:.1f}s
- Frame 6 (bottom-right): ~{duration_s * 0.95:.1f}s

Analyze these 6 frames carefully:
1. What is visible in each frame? Look for text, hotel/restaurant signs, landmarks, head turns, camera pans, streetscapes, stops.
2. What are the key editorial sub-events and their approximate [start_s, end_s] timestamps?
3. Which frame/timestamp range contains a prominent named landmark, hotel, restaurant, monument, or historical wall?

Return ONLY valid JSON matching this schema:
{{
  "sub_events": [
    {{"segment": [start_s, end_s], "description": "concise description of action/setting"}}
  ],
  "landmarks": [
    {{"name": "Landmark Name", "type": "hotel|restaurant|sign|ruin|vista", "timestamp_range": [start_s, end_s], "details": "visible features"}}
  ]
}}
"""
    for attempt in range(1, 4):
        try:
            resp = client.models.generate_content(
                model=VISION_MODEL,
                contents=[img, prompt],
                config=types.GenerateContentConfig(response_mime_type="application/json")
            )
            text = resp.text.strip()
            data = json.loads(text)
            with open(cache_path, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2, ensure_ascii=False)
            return data
        except Exception as e:
            if attempt < 3:
                import time
                time.sleep(3.0 * attempt)
            else:
                print(f"Warning: Failed to analyze strip {strip_path.name}: {e}", file=sys.stderr)
                return {}


def process_project_subclips(project_dir: Path, force: bool = False):
    """Processes all video contact strips in project_dir and updates project_manifest.json and Storyboard.md."""
    manifest_path = project_dir / "project_manifest.json"
    proxy_dir = project_dir / ".proxies"

    if not manifest_path.exists():
        # Check catalog fallback
        for cand in project_dir.glob("04_Project_Catalog/*/*/project_manifest.json"):
            manifest_path = cand
            break

    if not manifest_path.exists():
        print(f"Error: No project_manifest.json found for {project_dir}", file=sys.stderr)
        return

    with open(manifest_path, "r", encoding="utf-8") as f:
        manifest = json.load(f)

    if not proxy_dir.exists():
        print(f"Error: No .proxies directory found in {project_dir}", file=sys.stderr)
        return

    client = None
    if genai and os.environ.get("GEMINI_API_KEY"):
        client = genai.Client()
    else:
        print("Warning: GEMINI_API_KEY not set or google-genai not installed. Skipping vision analysis.", file=sys.stderr)
        return

    media_items = manifest.get("media_inventory") or manifest.get("media_items", [])
    updated = False

    for item in media_items:
        if item.get("media_type") != "video":
            continue
        dur = item.get("duration_s", 0.0)
        if dur < 12.0:
            continue

        fname = item.get("filename", "")
        stem = Path(fname).stem
        strip_path = proxy_dir / f"{stem}_strip.jpg"
        if not strip_path.exists():
            continue

        cache_path = proxy_dir / f"{stem}_subclips.json"
        if not force and cache_path.exists() and (item.get("subclips") or item.get("sub_clips")):
            continue

        print(f"Analyzing {fname} ({dur:.1f}s) via contact strip...")
        res = analyze_clip_strip(strip_path, dur, client)
        if res:
            item.pop("sub_clips", None)
            item["subclips"] = res.get("sub_events", [])
            item["landmarks"] = res.get("landmarks", [])
            updated = True
            print(f"  -> Found {len(item['subclips'])} sub-events, {len(item['landmarks'])} landmarks.")

    if updated:
        with open(manifest_path, "w", encoding="utf-8") as f:
            json.dump(manifest, f, indent=2, ensure_ascii=False)
        print(f"Updated {manifest_path} with semantic subclip indices.")

        # Also update synced copy in 04_Project_Catalog if different
        cat_manifest = None
        for p in Path("04_Project_Catalog").glob(f"*/{project_dir.name}/project_manifest.json"):
            cat_manifest = p
            break
        if cat_manifest and cat_manifest != manifest_path:
            with open(cat_manifest, "w", encoding="utf-8") as f:
                json.dump(manifest, f, indent=2, ensure_ascii=False)
            print(f"Synced {cat_manifest}.")

        # Now inject subclip breakdown into Storyboard.md
        update_storyboard_media_log(project_dir, media_items)


def update_storyboard_media_log(project_dir: Path, media_items: list):
    """Enriches Section 3 of Storyboard.md with sub-clip breakdown and landmarks."""
    storyboard_path = project_dir / "Storyboard.md"
    if not storyboard_path.exists():
        return

    text = storyboard_path.read_text(encoding="utf-8")
    
    # Check if chronological media log exists
    header_pattern = r"(## 3\.\s*Chronological Media & GPS Log[^\n]*\n)"
    m = re.search(header_pattern, text)
    if not m:
        return

    # Build enriched log lines
    log_lines = []
    for item in media_items:
        fname = item.get("filename", "")
        dur = item.get("duration_s", 0.0)
        gps_str = f" (GPS: {item.get('qt_lat')}, {item.get('qt_lon')})" if item.get("qt_lat") else ""
        dur_str = f" [{dur}s]" if item.get("media_type") == "video" else " [Still]"
        log_lines.append(f"- `{fname}` — `{item.get('creation_time_utc', '')}`{dur_str}{gps_str}")
        
        # Add landmarks
        for l in item.get("landmarks", []):
            t_rng = l.get("timestamp_range", [])
            rng_str = f"{t_rng[0]:.1f}s - {t_rng[1]:.1f}s" if len(t_rng) == 2 else ""
            log_lines.append(f"  * **[KEY LANDMARK]** `{l.get('name')}` ({l.get('type')}) at `{rng_str}`: {l.get('details', '')}")
            
        # Add sub-clips
        for sc in item.get("sub_clips", []):
            seg = sc.get("segment", [])
            seg_str = f"{seg[0]:.1f}s - {seg[1]:.1f}s" if len(seg) == 2 else ""
            log_lines.append(f"  * `{seg_str}`: {sc.get('description')}")

    # Replace everything from Section 3 up to Section 4 or end of file
    sec4_match = re.search(r"(\n## 4\.\s*Multi-Language Voice-Over)", text)
    if sec4_match:
        before = text[:m.end()]
        after = text[sec4_match.start():]
        new_text = before + "\n" + "\n".join(log_lines) + "\n" + after
    else:
        before = text[:m.end()]
        new_text = before + "\n" + "\n".join(log_lines) + "\n"

    storyboard_path.write_text(new_text, encoding="utf-8")
    print(f"Enriched {storyboard_path.name} Section 3 with sub-clip timelines.")

    # Also update catalog copy if exists
    for p in Path("04_Project_Catalog").glob(f"*/{project_dir.name}/Storyboard.md"):
        p.write_text(new_text, encoding="utf-8")
        print(f"Synced {p}.")


def main():
    parser = argparse.ArgumentParser(description="Analyze video contact strips to index sub-events and landmarks.")
    parser.add_argument("--project-dir", required=True, type=Path, help="Path to project folder in ~/Movies/YEAR/<project>")
    parser.add_argument("--force", action="store_true", help="Force re-analysis even if cached")
    args = parser.parse_args()

    project_dir = args.project_dir.expanduser().resolve()
    process_project_subclips(project_dir, force=args.force)


if __name__ == "__main__":
    main()
